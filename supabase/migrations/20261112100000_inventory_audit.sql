-- Audit Inventory (5a): every product change, from any path (screen, toggle, manual creation,
-- import, maintenance SQL), is recorded by the database itself, append-only.
-- Approved by Yuri on 28/10 and 03/11 (DECISOES.md). History starts when this is applied;
-- nothing before it exists. No existing row is changed by this migration.
--
-- One audit row per product per transaction, with the full product before and after (BINs
-- included). Edits and imports rewrite BINs as delete + insert; comparing whole snapshots at
-- commit time records only products that really changed, so a re-import of the same sheet
-- records nothing.

create table public.inventory_audit (
  id bigint generated by default as identity primary key,
  changed_at timestamptz not null default now(),
  brand_code text not null,
  actor_id uuid,           -- auth user who made the change; null for maintenance/service work
  actor_role text not null, -- database role of the request: authenticated, service_role, postgres
  before jsonb,            -- null: product created
  after jsonb,             -- null: product deleted
  check (before is not null or after is not null)
);
create index inventory_audit_changed_at_idx on public.inventory_audit(changed_at);
create index inventory_audit_brand_code_idx on public.inventory_audit(brand_code, changed_at);

alter table public.inventory_audit enable row level security;
revoke all on public.inventory_audit from public, anon, authenticated;
grant select on public.inventory_audit to authenticated;
create policy inventory_audit_admin_read on public.inventory_audit for select to authenticated
using ((select public.is_admin()));

-- Append-only, for every role including service_role (which bypasses RLS).
create or replace function private.inventory_audit_append_only()
returns trigger language plpgsql set search_path = ''
as $$
begin
  raise exception 'Audit Inventory is append-only';
end;
$$;
create trigger inventory_audit_no_update before update or delete on public.inventory_audit
for each row execute function private.inventory_audit_append_only();
create trigger inventory_audit_no_truncate before truncate on public.inventory_audit
for each statement execute function private.inventory_audit_append_only();

-- Product as the Inventory screen shows it, BINs sorted; null when it does not exist.
create or replace function private.inventory_snapshot(p_code text)
returns jsonb language sql stable security definer set search_path = ''
as $$
  select jsonb_build_object(
    'brand_name', i.brand_name, 'category', i.category, 'category1', i.category1,
    'bpu', i.bpu, 'pallet_size', i.pallet_size, 'weight_avg', i.weight_avg,
    'brand_active', i.brand_active, 'warehouse_id', i.warehouse_id, 'warehouse', w.name,
    'bins', coalesce((select jsonb_agg(b.bin_location order by b.bin_location)
      from public.item_bin_locations b where b.brand_code = i.brand_code), '[]'::jsonb))
  from public.inventory_items i left join public.warehouses w on w.id = i.warehouse_id
  where i.brand_code = p_code;
$$;

-- First touch of a product in a transaction keeps its "before" and who is changing it.
create table private.inventory_audit_pending (
  tx bigint not null,
  brand_code text not null,
  before jsonb,
  actor_id uuid,
  actor_role text not null,
  primary key (tx, brand_code)
);
revoke all on private.inventory_audit_pending from public, anon, authenticated;

create or replace function private.inventory_audit_stage()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  v_code text;
begin
  foreach v_code in array array_remove(array[
    case when tg_op <> 'INSERT' then old.brand_code end,
    case when tg_op <> 'DELETE' then new.brand_code end], null) loop
    insert into private.inventory_audit_pending(tx, brand_code, before, actor_id, actor_role)
    values (pg_catalog.txid_current(), v_code, private.inventory_snapshot(v_code), auth.uid(),
      coalesce(nullif(pg_catalog.current_setting('role', true), 'none'), session_user))
    on conflict do nothing;
  end loop;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

-- Runs at commit: compares each staged product with how it ended and records real changes.
create or replace function private.inventory_audit_flush()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  p record;
  v_after jsonb;
begin
  for p in delete from private.inventory_audit_pending where tx = pg_catalog.txid_current() returning * loop
    v_after := private.inventory_snapshot(p.brand_code);
    if p.before is distinct from v_after then
      insert into public.inventory_audit(brand_code, actor_id, actor_role, before, after)
      values (p.brand_code, p.actor_id, p.actor_role, p.before, v_after);
    end if;
  end loop;
  return null;
end;
$$;

-- BEFORE row triggers see the product as it was before this statement touched it.
create trigger inventory_audit_stage before insert or update or delete on public.inventory_items
for each row execute function private.inventory_audit_stage();
create trigger inventory_audit_stage before insert or update or delete on public.item_bin_locations
for each row execute function private.inventory_audit_stage();
create constraint trigger inventory_audit_flush after insert or update or delete on public.inventory_items
deferrable initially deferred for each row execute function private.inventory_audit_flush();
create constraint trigger inventory_audit_flush after insert or update or delete on public.item_bin_locations
deferrable initially deferred for each row execute function private.inventory_audit_flush();

revoke all on function private.inventory_audit_append_only(), private.inventory_snapshot(text),
  private.inventory_audit_stage(), private.inventory_audit_flush() from public, anon, authenticated;
